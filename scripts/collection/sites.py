# Public suffixes of two labels that occur in the screened Tranco range. Taking
# the last two labels alone made every .co.uk site the same "co.uk" site.
TWO_LABEL_SUFFIXES = {
    "co.uk", "org.uk", "ac.uk", "gov.uk", "com.au", "net.au", "org.au", "co.jp",
    "ne.jp", "or.jp", "com.br", "com.cn", "com.tw", "com.hk", "co.in", "co.kr",
    "com.tr", "com.mx", "co.za", "com.ar", "com.sg", "co.id", "com.ua", "co.nz",
    "com.vn", "com.pl", "co.il", "com.my", "com.co", "com.pe", "com.sa", "com.eg",
}


def registrable(host):
    """The registrable domain of a hostname; good enough to keep pools disjoint."""
    host = (host or "").lower().strip(".")
    if host.startswith("www."):
        host = host[4:]
    labels = host.split(".")
    n = 3 if ".".join(labels[-2:]) in TWO_LABEL_SUFFIXES else 2
    return ".".join(labels[-n:])


def monitored_domains(site_set=""):
    return {registrable(urlparse(u).hostname) for u in load_monitored(site_set).values()}


def load_monitored(site_set=""):
    """The monitored sites: MONITORED for tb-main, else sites/<set>/monitored.txt."""
    if not site_set:
        return dict(MONITORED)
    pool = load_pool("monitored", site_set)
    if not pool:
        raise FileNotFoundError(f"no monitored sites in {os.path.join(SITES_DIR, site_set)}; "
                                f"run build_site_lists.py --site-set {site_set}")
    return pool


def load_pool(name, site_set=""):
    """Read sites/[<set>/]<name>.txt: one 'label url' per line, '#' comments allowed."""
    path = os.path.join(SITES_DIR, site_set, f"{name}.txt")
    pool = {}
    if not os.path.exists(path):
        return pool
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            label, url = line.split()
            pool[label] = url
    return pool
